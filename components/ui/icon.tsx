export type IconName = keyof typeof ICONS;

interface IconProps {
    name: IconName;
    size?: number;
    color?: string;
    style?: StyleProp<ViewStyle>;
    accessibilityLabel?: string;
}

export const Icon = ({ name, size = 24, color, style, accessibilityLabel }: IconProps) => {
    const entry = ICONS[name];
    const solid = 'solid' in entry;
    return (
        <HugeiconsIcon
            icon={solid ? entry.icon : entry}
            size={size}
            color={color}
            fill={solid ? color : 'none'}
            style={style}
            accessible={!!accessibilityLabel}
            accessibilityLabel={accessibilityLabel}
        />
    );
};
